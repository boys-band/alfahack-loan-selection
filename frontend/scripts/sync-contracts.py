"""Sync only public DTO/operation graph. Run from frontend; requires PyYAML."""
import hashlib, json, pathlib, re, yaml
root = pathlib.Path(__file__).resolve().parents[2]
out = root / 'frontend'

def write_snapshot(path, text):
    path.write_text(text, encoding='utf-8', newline='\n')
schema = yaml.safe_load((root/'contracts/schemas.yaml').read_text(encoding='utf-8'))
ops = {}
roots = {'Problem'}
for name in ['applications', 'catalog']:
    doc = yaml.safe_load((root/f'contracts/openapi/{name}.yaml').read_text(encoding='utf-8'))
    for path, methods in doc['paths'].items():
        if not path.startswith('/v2/'): continue
        for method, op in methods.items():
            if method not in ['get','post','patch']: continue
            body = op.get('requestBody',{}).get('content',{}).get('application/json',{}).get('schema',{}).get('$ref','').split('/')[-1] or None
            responses = {k: v['content']['application/json']['schema']['$ref'].split('/')[-1] for k,v in op['responses'].items() if k.startswith('2')}
            response = next(iter(responses.values()))
            roots.add(response)
            if body: roots.add(body)
            ops[op['operationId']] = dict(method=method.upper(),path=path,body=body,response=response,success=list(map(int,responses)),params=[{'name':p['name'],'location':p['in'],'required':p.get('required',False),'type':p['schema'].get('type','string')} for p in op.get('parameters',[]) if 'name' in p])
def refs(v):
    if isinstance(v,dict):
        if '$ref' in v: yield v['$ref'].split('/')[-1]
        for x in v.values(): yield from refs(x)
    elif isinstance(v,list):
        for x in v: yield from refs(x)
needed=set()
def visit(n):
    if n in needed:return
    needed.add(n)
    for dep in refs(schema['$defs'][n]):visit(dep)
for n in roots:visit(n)
snapshot={'$schema':'https://json-schema.org/draft/2020-12/schema','$id':'urn:alfa:public', '$defs':{k:v for k,v in schema['$defs'].items() if k in needed}}
write_snapshot((out/'contract/schemas.json'), json.dumps(snapshot,ensure_ascii=False,indent=2)+'\n')
write_snapshot((out/'contract/operations.json'), json.dumps(ops,ensure_ascii=False,indent=2)+'\n')
def typ(v):
    if '$ref' in v:return v['$ref'].split('/')[-1]
    if 'const' in v:return json.dumps(v['const'],ensure_ascii=False)
    if 'enum' in v:return ' | '.join(json.dumps(x) for x in v['enum'])
    if 'anyOf' in v:return '('+' | '.join(typ(x) for x in v['anyOf'])+')'
    if 'allOf' in v and 'type' not in v:
        parts=[typ(x) for x in v['allOf'] if '$ref' in x or 'type' in x]
        return ' & '.join(parts) or 'unknown'
    t=v.get('type')
    if t=='object':return '{ '+ '; '.join(json.dumps(k)+('' if k in v.get('required',[]) else '?')+': '+typ(x) for k,x in v.get('properties',{}).items())+' }'
    if t=='array':return 'Array<'+typ(v['items'])+'>'
    return {'integer':'number','number':'number','string':'string','boolean':'boolean','null':'null'}.get(t,'unknown')
code='// Generated by scripts/sync-contracts.py. Do not edit. Schema validates constraints at runtime.\n'
for k,v in snapshot['$defs'].items():code+=f'export type {k} = {typ(v)};\n'
code+='export interface Operations {\n'
for n,o in ops.items():
    p='{ '+ '; '.join(x['name']+('' if x['required'] else '?')+': '+('number' if x['type']=='integer' else 'string') for x in o['params'])+' }'
    code+=f'  {n}: {{ params: {p}; body: {o["body"] or "undefined"}; response: {o["response"]} }};\n'
code+='}\n'
write_snapshot((out/'src/api/generated.ts'), code)
examples={}
# Preserve the already shipped snapshot order and append new fixtures deterministically.
shipped_order = ['errors', 'payout-recovery', 'approved', 'declined', 'counteroffer',
                 'manual-review', 'information-and-versions', 'lifecycle']
for file in sorted((root/'contracts/examples').glob('*.json'),
                   key=lambda path: (shipped_order.index(path.stem) if path.stem in shipped_order else len(shipped_order), path.stem)):
    d=json.loads(file.read_text(encoding='utf-8'))
    if 'exchanges' in d: examples[file.stem]=d['exchanges']
write_snapshot((out/'contract/examples.json'), json.dumps(examples,ensure_ascii=False,indent=2)+'\n')
seed=json.loads((root/'contracts/examples/seed.json').read_text(encoding='utf-8'))
write_snapshot((out/'contract/seed.json'), json.dumps({k:v for k,v in seed.items() if k in ['companies','products','accounts']},ensure_ascii=False,indent=2)+'\n')
print(f'Synced {len(ops)} public operations, {len(needed)} DTOs')

# Hash canonical LF bytes so Windows and Linux checkouts produce the same revision.
files=["contracts/schemas.yaml","contracts/openapi/applications.yaml","contracts/openapi/catalog.yaml"]
write_snapshot((out/"contract/source-hashes.json"), json.dumps({f:hashlib.sha256((root/f).read_bytes().replace(b'\r\n', b'\n')).hexdigest() for f in files},indent=2)+"\n")
